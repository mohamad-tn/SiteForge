export const PLATFORM_LANGS = ["ar", "en"] as const;
export type PlatformLang = (typeof PLATFORM_LANGS)[number];

export const PLATFORM_LANG_KEY = "sf-platform-lang";
/** Legacy key used by older dashboard builds — migrated on read. */
export const PLATFORM_LANG_LEGACY_KEY = "siteforge-ui-lang";
export const PLATFORM_LANG_EVENT = "sf-platform-lang";

export function isPlatformLang(v: unknown): v is PlatformLang {
  return v === "ar" || v === "en";
}

export function platformDir(lang: PlatformLang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function readStoredPlatformLang(): PlatformLang {
  if (typeof window === "undefined") return "ar";
  const next = localStorage.getItem(PLATFORM_LANG_KEY);
  if (isPlatformLang(next)) return next;
  const legacy = localStorage.getItem(PLATFORM_LANG_LEGACY_KEY);
  if (isPlatformLang(legacy)) {
    localStorage.setItem(PLATFORM_LANG_KEY, legacy);
    return legacy;
  }
  return "ar";
}

export function writeStoredPlatformLang(lang: PlatformLang) {
  localStorage.setItem(PLATFORM_LANG_KEY, lang);
  localStorage.setItem(PLATFORM_LANG_LEGACY_KEY, lang); // keep legacy listeners in sync during migration
  window.dispatchEvent(new Event(PLATFORM_LANG_EVENT));
  window.dispatchEvent(new Event("siteforge-ui-lang"));
}

